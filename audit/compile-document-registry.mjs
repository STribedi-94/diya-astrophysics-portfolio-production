/**
 * AMP Document Registry Compiler CLI
 *
 * Compiles all configured document assets and writes a deterministic,
 * lightweight JavaScript registry module.
 */

import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";

import { compileDocumentRegistry } from "./amp/compiler/document-compiler.mjs";

const OUTPUT_DIRECTORY = path.resolve(
    "audit/amp/generated"
);

const OUTPUT_FILE = path.join(
    OUTPUT_DIRECTORY,
    "document-records.generated.mjs"
);

function createGeneratedModule(records) {
    const serializedRecords = JSON.stringify(
        records,
        null,
        4
    );

    return `/**
 * AUTO-GENERATED AMP DOCUMENT REGISTRY
 *
 * Generated by audit/compile-document-registry.mjs.
 * Do not edit this file manually.
 */

export const documentRecords = Object.freeze(
    ${serializedRecords}
);
`;
}

async function main() {
    const records = await compileDocumentRegistry();

    await mkdir(OUTPUT_DIRECTORY, {
        recursive: true
    });

    await writeFile(
        OUTPUT_FILE,
        createGeneratedModule(records),
        "utf8"
    );

    console.log("\nAMP Document Registry Compiler");
    console.log("==============================");
    console.log(`Records compiled: ${records.length}`);
    console.log(`Output: ${OUTPUT_FILE}`);

    for (const record of records) {
        console.log(
            `${record.id} -> ${record.source.key}`
        );
    }

    if (records.length !== 11) {
        throw new Error(
            `Expected 11 document records but compiled ${records.length}.`
        );
    }

    console.log("\nDocument registry compilation succeeded.");
}

main().catch((error) => {
    console.error("\nDocument registry compilation failed.");
    console.error(
        error instanceof Error
            ? error.stack
            : String(error)
    );
    process.exitCode = 1;
});
/**
 * AMP Document Registry Compiler CLI
 *
 * Compiles all configured document assets and writes two deterministic
 * registry modules:
 *
 * 1. A Node-facing JavaScript module for the AMP engineering toolkit.
 * 2. A browser-facing TypeScript module for the React application.
 *
 * Both outputs are generated from the same authoritative document records.
 */

import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";

import { compileDocumentRegistry } from "./amp/compiler/document-compiler.mjs";

const AUDIT_OUTPUT_DIRECTORY = path.resolve(
  "audit/amp/generated",
);

const AUDIT_OUTPUT_FILE = path.join(
  AUDIT_OUTPUT_DIRECTORY,
  "document-records.generated.mjs",
);

const WEBSITE_OUTPUT_DIRECTORY = path.resolve(
  "src/generated/amp",
);

const WEBSITE_OUTPUT_FILE = path.join(
  WEBSITE_OUTPUT_DIRECTORY,
  "document-records.generated.ts",
);

function serializeRecords(records) {
  return JSON.stringify(records, null, 2);
}

function createAuditGeneratedModule(records) {
  return `/**
 * AUTO-GENERATED AMP DOCUMENT REGISTRY
 *
 * Generated by audit/compile-document-registry.mjs.
 * Do not edit this file manually.
 */

export const documentRecords = Object.freeze(
  ${serializeRecords(records)}
);
`;
}

function createWebsiteGeneratedModule(records) {
  return `/**
 * AUTO-GENERATED AMP DOCUMENT REGISTRY
 *
 * Browser-safe registry generated by
 * audit/compile-document-registry.mjs.
 *
 * Do not edit this file manually.
 */

export const documentRecords = Object.freeze(
  ${serializeRecords(records)} as const,
);
`;
}

async function writeGeneratedFile(
  outputDirectory,
  outputFile,
  contents,
) {
  await mkdir(outputDirectory, {
    recursive: true,
  });

  await writeFile(
    outputFile,
    contents,
    "utf8",
  );
}

async function main() {
  const records = await compileDocumentRegistry();

  await Promise.all([
    writeGeneratedFile(
      AUDIT_OUTPUT_DIRECTORY,
      AUDIT_OUTPUT_FILE,
      createAuditGeneratedModule(records),
    ),
    writeGeneratedFile(
      WEBSITE_OUTPUT_DIRECTORY,
      WEBSITE_OUTPUT_FILE,
      createWebsiteGeneratedModule(records),
    ),
  ]);

  console.log("\nAMP Document Registry Compiler");
  console.log("==============================");
  console.log(`Records compiled: ${records.length}`);
  console.log(`Audit output: ${AUDIT_OUTPUT_FILE}`);
  console.log(`Website output: ${WEBSITE_OUTPUT_FILE}`);

  for (const record of records) {
    console.log(
      `${record.id} -> ${record.source.key}`,
    );
  }

  console.log("\nDocument registry compilation succeeded.");
}

main().catch((error) => {
  console.error("\nDocument registry compilation failed.");
  console.error(
    error instanceof Error
      ? error.stack
      : String(error),
  );
  process.exitCode = 1;
});